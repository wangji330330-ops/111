def main():
    data = []
    seen = set()
    errs = []
    cats = collections.OrderedDict()
    for rec in RAW:
        name, cat, nature, meridian, fx, usage, caution = rec
        if name in seen:
            errs.append("药名重复: " + name)
        seen.add(name)
        if not fx:
            errs.append("无功效: " + name)
        for item in fx:
            if "，" in item or "," in item or "。" in item:
                errs.append("功效项内部含标点: %s -> %s" % (name, item))
            if len(item) < 2:
                errs.append("功效项过短: %s -> %s" % (name, item))
        cats.setdefault(cat, []).append(name)
        data.append({
            "name": name, "cat": cat, "nature": nature, "meridian": meridian,
            "fx": list(fx), "usage": usage, "caution": caution,
        })

    # 检查同分类下是否存在完全相同的功效组合（会造成多选干扰项歧义）
    # 说明：部分药材（如甘遂/京大戟、三棱/莪术）在教材中功效本就相同，
    # 这里只统计并输出，程序端会自动把同组药材排除在彼此的干扰项之外。
    combos = {}
    for d in data:
        key = (d["cat"], "|".join(sorted(d["fx"])))
        if key in combos:
            errs.append("同组功效相同(程序端已处理): %s 与 %s" % (d["name"], combos[key]))
        combos[key] = d["name"]

    out = {
        "meta": {
            "title": "中药学复习题库",
            "count": len(data),
            "categories": list(cats.keys()),
            "synonyms": SYNONYMS,
        },
        "herbs": data,
    }
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "herbs.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)

    print("herbs total:", len(data))
    print("categories:", len(cats))
    total_fx = sum(len(d["fx"]) for d in data)
    print("function items:", total_fx, " avg:", round(total_fx / len(data), 2))
    for c, names in cats.items():
        print("  %-28s %3d" % (c, len(names)))
    if errs:
        print("")
        print("VALIDATION PROBLEMS:")
        for e in errs:
            print("  !", e.encode("unicode_escape").decode("ascii"))
    else:
        print("")
        print("VALIDATION OK - no problems.")

if __name__ == "__main__":
    main()
