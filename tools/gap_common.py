def main():
    with io.open(os.path.join(ROOT, "herbs.json"), encoding="utf-8") as f:
        have = [h["name"] for h in json.load(f)["herbs"]]
    haveset = set(have)

    # 去重后的候选总表
    allcand = []
    seen = set()
    for cat, names in CANDIDATES.items():
        for n in names:
            if n not in seen:
                seen.add(n)
                allcand.append((cat, n))

    lines = []
    lines.append("现有题库: %d 味" % len(have))
    lines.append("A∪B 候选清单（去重后）: %d 味" % len(allcand))
    missing = [(c, n) for c, n in allcand if n not in haveset]
    lines.append("已覆盖: %d 味" % (len(allcand) - len(missing)))
    lines.append("需要新增: %d 味" % len(missing))
    lines.append("")
    lines.append("=== 需要新增的药味（按大类）===")
    bycat = {}
    for c, n in missing:
        bycat.setdefault(c, []).append(n)
    for cat in CANDIDATES:
        if cat in bycat:
            lines.append("【%s】%d 味: %s" % (cat, len(bycat[cat]), "、".join(bycat[cat])))
    lines.append("")
    lines.append("=== 现有题库里、候选清单未列出的药味（说明题库已超出 A∪B 范围）===")
    extra = [n for n in have if n not in seen]
    lines.append("%d 味: %s" % (len(extra), "、".join(extra)))

    out = os.path.join(ROOT, "review", "gap_common.txt")
    io.open(out, "w", encoding="utf-8").write("\n".join(lines))
    print("现有 %d 味 | 候选 %d 味 | 需新增 %d 味 | 题库已超出候选 %d 味"
          % (len(have), len(allcand), len(missing), len(extra)))
    print("明细: %s" % out)


if __name__ == "__main__":
    main()
