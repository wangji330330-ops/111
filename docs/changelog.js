/* 把版本日志渲染到一个容器里（紧凑列表） */
function renderChangelog(containerId) {
  const el = document.getElementById(containerId);
  if (!el) return;
  el.innerHTML = CHANGELOG.map((r, i) => `
    <div class="cl-item${i === 0 ? ' latest' : ''}">
      <div class="cl-head">
        <span class="cl-ver">v${r.v}</span>
        <span class="cl-title">${r.title}</span>
        <span class="cl-date">${r.date}</span>
      </div>
      <ul class="cl-list">${r.items.map(x => `<li>${x}</li>`).join('')}</ul>
    </div>`).join('');
}

function openChangelog() {
  const box = document.getElementById('clModal');
  if (!box) return;
  renderChangelog('clBody');
  box.classList.add('show');
  document.body.style.overflow = 'hidden';
}
function closeChangelog() {
  const box = document.getElementById('clModal');
  if (!box) return;
  box.classList.remove('show');
  document.body.style.overflow = '';
}
